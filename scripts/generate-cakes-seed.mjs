import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const seedRows = JSON.parse(
  readFileSync(join(root, "lib", "data", "cakes-seed-data.json"), "utf8"),
);

function sqlString(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

const inserts = seedRows.map((row) => {
  return `insert into cakes (
  slug,
  price_per_pound,
  min_weight,
  notice_days,
  sort_order,
  is_active,
  tags,
  image_paths,
  translations
) values (
  ${sqlString(row.slug)},
  ${row.price_per_pound},
  ${row.min_weight},
  ${row.notice_days},
  ${row.sort_order},
  ${row.is_active},
  array[${row.tags.map((tag) => sqlString(tag)).join(", ")}]::text[],
  array[${row.image_paths.map((path) => sqlString(path)).join(", ")}]::text[],
  ${sqlString(JSON.stringify(row.translations))}::jsonb
) on conflict (slug) do nothing;`;
});

const sql = `-- Auto-generated by scripts/generate-cakes-seed.mjs — do not edit manually
${inserts.join("\n\n")}

alter table reviews drop constraint if exists reviews_cake_slug_check;

alter table reviews
  add constraint reviews_cake_slug_fkey
  foreign key (cake_slug) references cakes (slug)
  on delete restrict;
`;

writeFileSync(join(root, "supabase", "migrations", "004_cakes_seed.sql"), sql);
console.log("Wrote supabase/migrations/004_cakes_seed.sql");
